import { graphCorpusJsonShapeLines } from './graph-corpus-emitted-json-shape-lines.js';

export const graphCorpusIndexModuleLines: readonly string[] = [
  '/**',
  ' * Graph corpus — typed loader for generated JSON data.',
  ' *',
  ' * @remarks',
  ' * Generated by the graph corpus JSON writer. Imports raw JSON data and',
  ' * re-exports it with the generator-owned TypeScript interfaces, validating',
  ' * the kind discriminants, kind-qualified node ids, and edge type literals',
  ' * at load (ADR-086 union-literal narrowing).',
  ' */',
  "import { readFileSync } from 'node:fs';",
  '',
  'import type {',
  '  GraphCorpus,',
  '  GraphCorpusEdge,',
  '  GraphCorpusEdgeType,',
  '  GraphCorpusNode,',
  '  GraphCorpusNodeId,',
  '  GraphCorpusSequence,',
  '  GraphCorpusUnitLessonRun,',
  '  GraphCorpusStats,',
  '  GraphCorpusDroppedEdge,',
  '  GraphCorpusDroppedDuplicate,',
  "} from './types.js';",
  '',
  "const dataUrl = new URL('./data.json', import.meta.url);",
  "const data: JsonGraphCorpus = JSON.parse(readFileSync(dataUrl, 'utf8'));",
  '',
  ...graphCorpusJsonShapeLines,
  '',
  "const NODE_KINDS = ['unit', 'thread', 'lesson', 'misconception', 'keyword'] as const;",
  '',
  "const EDGE_TYPES = ['prerequisiteFor', 'containsUnit', 'containsLesson', 'addressesMisconception', 'containsKeyword'] as const;",
  '',
  'function isEdgeType(value: string): value is GraphCorpusEdgeType {',
  '  return EDGE_TYPES.some((edgeType) => edgeType === value);',
  '}',
  '',
  '/** Narrows a raw id to the kind-qualified template type for one kind. */',
  'function toKindQualifiedId<Kind extends (typeof NODE_KINDS)[number]>(',
  '  kind: Kind,',
  '  id: string,',
  '): `${Kind}:${string}` {',
  '  if (!id.startsWith(`${kind}:`)) {',
  '    throw new TypeError(',
  '      `Graph-corpus node id "${id}" does not carry its kind qualifier "${kind}:"`,',
  '    );',
  '  }',
  '  return id as `${Kind}:${string}`;',
  '}',
  '',
  '/**',
  ' * Constructs the generator-owned node union from a raw JSON node,',
  ' * discriminating on `kind` and narrowing the kind-qualified id at load',
  ' * (ADR-086 union-literal narrowing).',
  ' */',
  'function toNode(node: JsonGraphCorpusNode): GraphCorpusNode {',
  '  switch (node.kind) {',
  "    case 'unit':",
  '      return {',
  "        kind: 'unit',",
  "        id: toKindQualifiedId('unit', node.id),",
  '        unitSlug: node.unitSlug,',
  '        unitTitle: node.unitTitle,',
  '        subject: node.subject,',
  '        keyStage: node.keyStage,',
  '        year: node.year,',
  '        priorKnowledge: node.priorKnowledge,',
  '        threadSlugs: node.threadSlugs,',
  '      };',
  "    case 'thread':",
  '      return {',
  "        kind: 'thread',",
  "        id: toKindQualifiedId('thread', node.id),",
  '        threadSlug: node.threadSlug,',
  '        title: node.title,',
  '        firstYear: node.firstYear,',
  '        lastYear: node.lastYear,',
  '      };',
  "    case 'lesson':",
  '      return {',
  "        kind: 'lesson',",
  "        id: toKindQualifiedId('lesson', node.id),",
  '        lessonSlug: node.lessonSlug,',
  '        lessonTitle: node.lessonTitle,',
  '        subject: node.subject,',
  '        keyStage: node.keyStage,',
  '      };',
  "    case 'misconception':",
  '      return {',
  "        kind: 'misconception',",
  "        id: toKindQualifiedId('misconception', node.id),",
  '        misconception: node.misconception,',
  '        response: node.response,',
  '      };',
  "    case 'keyword':",
  '      return {',
  "        kind: 'keyword',",
  "        id: toKindQualifiedId('keyword', node.id),",
  '        term: node.term,',
  '        description: node.description,',
  '        frequency: node.frequency,',
  '        firstYear: node.firstYear,',
  '        subjects: node.subjects,',
  '      };',
  '    default:',
  '      throw new TypeError(`Unexpected graph-corpus node kind: ${JSON.stringify(node)}`);',
  '  }',
  '}',
  '',
  'function toNodeId(value: string): GraphCorpusNodeId {',
  '  const kind = NODE_KINDS.find((candidate) => value.startsWith(`${candidate}:`));',
  '  if (kind === undefined) {',
  '    throw new TypeError(`Unexpected graph-corpus node id (missing kind prefix): ${value}`);',
  '  }',
  '  return toKindQualifiedId(kind, value);',
  '}',
  '',
  'function toEdge(edge: JsonGraphCorpusEdge): GraphCorpusEdge {',
  '  if (!isEdgeType(edge.type)) {',
  '    throw new TypeError(`Unexpected graph-corpus edge type: ${edge.type}`);',
  '  }',
  '  return {',
  '    source: toNodeId(edge.source),',
  '    type: edge.type,',
  '    target: toNodeId(edge.target),',
  '  };',
  '}',
  '',
  '/** Narrows one sequence, validating the kind-qualified thread and unit ids at load. */',
  'function toSequence(sequence: JsonSequence): GraphCorpusSequence {',
  '  return {',
  "    threadId: toKindQualifiedId('thread', sequence.threadId),",
  '    subject: sequence.subject,',
  '    placements: sequence.placements.map((placement) => ({',
  "      unitId: toKindQualifiedId('unit', placement.unitId),",
  '      year: placement.year,',
  '    })),',
  '  };',
  '}',
  '',
  '/** Narrows one unit-lesson run, validating the kind-qualified unit and lesson ids at load. */',
  'function toUnitLessonRun(run: JsonUnitLessonRun): GraphCorpusUnitLessonRun {',
  '  return {',
  "    unitId: toKindQualifiedId('unit', run.unitId),",
  "    lessonIds: run.lessonIds.map((lessonId) => toKindQualifiedId('lesson', lessonId)),",
  '  };',
  '}',
  '',
  'function createGraphCorpus(graph: JsonGraphCorpus): GraphCorpus {',
  '  return {',
  '    version: graph.version,',
  '    generatedAt: graph.generatedAt,',
  '    sourceVersion: graph.sourceVersion,',
  '    stats: graph.stats,',
  '    nodes: graph.nodes.map(toNode),',
  '    edges: graph.edges.map(toEdge),',
  '    sequences: graph.sequences.map(toSequence),',
  '    unitLessonRuns: graph.unitLessonRuns.map(toUnitLessonRun),',
  '    droppedEdges: graph.droppedEdges,',
  '    droppedDuplicates: graph.droppedDuplicates,',
  '    seeAlso: graph.seeAlso,',
  '  };',
  '}',
  '',
  '/**',
  ' * The bulk curriculum graph corpus (unit, thread, lesson, misconception,',
  ' * and keyword nodes; prerequisiteFor and',
  ' * thread→unit→lesson→{misconception, keyword} chain edges; ordered',
  ' * thread→unit placement sequences).',
  ' *',
  ' * @remarks',
  ' * One identity space surfaced through bounded query views (Decision A). Node',
  ' * ids are kind-qualified (`unit:<unitSlug>`, `thread:<threadSlug>`,',
  ' * `lesson:<lessonSlug>`, `misconception:<lessonSlug>#<hash16>`,',
  ' * `keyword:<normalised-term>`); edge endpoints reference those ids; the',
  ' * corpus has zero dangling endpoints, so it constructs in `createGraphView`',
  ' * without throwing.',
  ' */',
  'export const graphCorpus: GraphCorpus = createGraphCorpus(data);',
  '',
  'export type {',
  '  GraphCorpus,',
  '  GraphCorpusNode,',
  '  GraphCorpusUnitNode,',
  '  GraphCorpusThreadNode,',
  '  GraphCorpusLessonNode,',
  '  GraphCorpusMisconceptionNode,',
  '  GraphCorpusKeywordNode,',
  '  GraphCorpusEdge,',
  '  GraphCorpusEdgeType,',
  '  GraphCorpusNodeId,',
  '  GraphCorpusUnitNodeId,',
  '  GraphCorpusThreadNodeId,',
  '  GraphCorpusLessonNodeId,',
  '  GraphCorpusMisconceptionNodeId,',
  '  GraphCorpusKeywordNodeId,',
  '  GraphCorpusStats,',
  '  GraphCorpusNodeKindCounts,',
  '  GraphCorpusEdgeTypeCounts,',
  '  GraphCorpusDroppedEdge,',
  '  GraphCorpusDroppedDuplicate,',
  '  GraphCorpusSequence,',
  '  GraphCorpusSequencePlacement,',
  '  GraphCorpusUnitLessonRun,',
  "} from './types.js';",
  '',
];
